/* 静的な配列の初期化子に**文字列リテラル**が出てくる形の，残っていた族。
 *
 * cc15q は「構造体の中の char 配列」まで直したが，**多次元の char 配列**
 * が残っていた (staticstr.c の註)。ginit() が多次元を平らに畳んでから
 * 要素を読むので，畳んだ後の要素型が char になり，ginit1() の「対象が
 * 配列なら実体を並べる」が効かない。要素 1 つに 4 バイトの再配置が
 * 書かれて中身がアドレスになる —— 台帳で bad と呼ぶ状態だった。
 *
 * **cc15s で直した** (docs/stage017-cc.md 33 章)。畳んでよいかを
 * 「`{` の次が `{` か文字列か」で決める。そうなら下位の対象そのものを
 * 初期化しているので畳まない。そうでなければ平らな並びなので今まで
 * どおり畳む —— **出るバイト列は変わらない**。
 *
 * ここは族を**まとめて**測る。1 つの形で確かめて族ぜんぶが無事だと
 * 思ったのが 3 度の誤りの元だった (27.4)。畳む道 (7 / 8) と，直しで
 * 壊していないこと (6 / 9 / 10) も一緒に見る。
 *
 * 11〜14 は**波括弧の省略** (C89 6.5.7)。下位の波括弧は途中から省いて
 * よいので，「1 つ目が `{` なら全体を畳まない」と決めると後ろの数が
 * 配列の幅で書かれる。レビューで指摘を受けて足した —— 直しで**別の
 * 正しい形を壊していた** (33.6)。 */
int putc(int c);

struct S { char a[8]; };

static char m2[2][8] = { "ab", "cd" };         /* 1 台帳の bad だった形 */
static char m0[][8]  = { "ab", "cd", "ef" };   /* 2 外側の数を書かない */
static char m3[3][8] = { "ab", "cd" };         /* 3 足りない分の埋め */
static char nb[2][8] = { {'a','b'}, {'c'} };   /* 4 入れ子の波括弧 */
static char b1[8]    = { "ab" };               /* 5 1 次元を波括弧で */
static char p1[8]    = "ab";                   /* 6 波括弧なし (前から通る) */
static int  fi[2][2] = { 1, 2, 3, 4 };         /* 7 平らな並び (畳む道) */
static int  ni[2][2] = { {1,2}, {3,4} };       /* 8 入れ子の int */
static struct S st   = { "xy" };               /* 9 構造体の中 (cc15q) */
static char *pp[2]   = { "gh", "ij" };         /* 10 ポインタの配列 */
static int  el[2][2] = { {1,2}, 3, 4 };        /* 11 途中から波括弧を省く */
static int  e2[2][2] = { 1, {2,3}, 4 };        /* 12 先頭だけ平ら */
static char ec[2][8] = { "ab", {'c','d'} };    /* 13 混ぜる */
static int  eo[][2]  = { {1,2}, 3, 4, 5 };     /* 14 外側の数を書かない */
static char tc[8]    = { "ab", };              /* 15 末尾のコンマ */
static char t2[2][8] = { "ab", "cd", };        /* 16 同 (多次元) */
static char d3[1][2][2] = { {'a','b','c','d'} };  /* 17 1 段深い省略 */
static char d4[2][2][4] = { {"ab","cd"}, {"ef","gh"} }; /* 18 3 次元の文字列 */
static int  sc[2][2] = { 1, {2}, 3, 4 };       /* 19 スカラを波括弧で囲む */
static char nt[1][8] = { {"ab",} };            /* 20 内側の末尾コンマ */

int t(void) {
  if (m2[0][0] != 'a' || m2[0][1] != 'b' || m2[0][2] != 0) return 1;
  if (m2[1][0] != 'c' || m2[1][1] != 'd') return 2;
  if (m0[0][0] != 'a' || m0[1][0] != 'c' || m0[2][0] != 'e') return 3;
  if (m3[0][0] != 'a' || m3[1][0] != 'c' || m3[2][0] != 0) return 4;
  if (nb[0][0] != 'a' || nb[0][1] != 'b' || nb[0][2] != 0) return 5;
  if (nb[1][0] != 'c' || nb[1][1] != 0) return 6;
  if (b1[0] != 'a' || b1[1] != 'b' || b1[2] != 0) return 7;
  if (p1[0] != 'a' || p1[2] != 0) return 8;
  if (fi[0][0] != 1 || fi[1][1] != 4) return 9;
  if (ni[0][0] != 1 || ni[1][1] != 4) return 10;
  if (st.a[0] != 'x' || st.a[2] != 0) return 11;
  if (pp[0][0] != 'g' || pp[1][0] != 'i') return 12;
  /* **波括弧の省略** (C89 6.5.7)。下位の波括弧は途中から省いてよい。
     1 つ目の形で全体を決めると，後ろの数が配列の幅で書かれる */
  if (el[0][0] != 1 || el[0][1] != 2) return 13;
  if (el[1][0] != 3 || el[1][1] != 4) return 14;
  if (e2[0][0] != 1 || e2[0][1] != 2) return 15;
  if (e2[1][0] != 3 || e2[1][1] != 4) return 16;
  if (ec[0][0] != 'a' || ec[0][2] != 0) return 17;
  if (ec[1][0] != 'c' || ec[1][1] != 'd' || ec[1][2] != 0) return 18;
  if (eo[0][0] != 1 || eo[1][0] != 3 || eo[2][0] != 5 || eo[2][1] != 0) return 19;
  /* 末尾のコンマ (C89 6.5.7)。一般の道は許すのに，文字列を波括弧で
     受ける道だけが拒んでいた (33.6) */
  if (tc[0] != 'a' || tc[1] != 'b' || tc[2] != 0) return 20;
  if (t2[0][0] != 'a' || t2[1][0] != 'c' || t2[1][2] != 0) return 21;
  /* **1 段深いところの省略。** ginit の側だけ直して ginit1 を直さないと
     内側の 4 つが char[2] の幅で書かれる (33.6) */
  if (d3[0][0][0] != 'a' || d3[0][0][1] != 'b') return 22;
  if (d3[0][1][0] != 'c' || d3[0][1][1] != 'd') return 23;
  if (d4[0][0][0] != 'a' || d4[0][1][0] != 'c') return 24;
  if (d4[1][0][0] != 'e' || d4[1][1][0] != 'g' || d4[1][1][2] != 0) return 25;
  /* **波括弧はいま埋めている対象を囲む。** {2} は a[0][1] を埋めるので
     あって行を埋めるのではない。トークンだけでなく位置も見る (33.6) */
  if (sc[0][0] != 1 || sc[0][1] != 2) return 26;
  if (sc[1][0] != 3 || sc[1][1] != 4) return 27;
  if (nt[0][0] != 'a' || nt[0][1] != 'b' || nt[0][2] != 0) return 28;
  return 0;
}

int main() {
  int r;
  r = t();
  if (r == 0) putc('y');
  else if (r < 10) { putc('0'); putc('0' + r); }
  else { putc('0' + r / 10); putc('0' + r % 10); }
  putc('\n');
  return 0;
}
