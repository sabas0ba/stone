// C89 7.1.3 の単純エスケープ 9 種と，8 進・16 進のエスケープを見る。
// 値そのものより「その綴りが受理され，正しい文字コードになる」ことが要点。
int main() {
  char *s;
  putc('\101'); putc('\x42'); putc('\x43');       // 8 進・16 進
  putc('0' + ('\n' == 10)); putc('0' + ('\t' == 9));
  putc('0' + ('\r' == 13)); putc('0' + ('\f' == 12));
  putc('0' + ('\v' == 11)); putc('0' + ('\a' == 7));
  putc('0' + ('\b' == 8)); putc('0' + ('\?' == 63));
  putc('0' + ('\\' == 92)); putc('0' + ('\'' == 39));
  putc('0' + ('\0' == 0)); putc('0' + ('\377' == 255));
  s = "\x48\x49\102\n";                            // 文字列の中でも同じ
  while (*s) { putc(*s); s++; }
  return 0;
}
