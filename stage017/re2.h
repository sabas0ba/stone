/* re2.h --- 正規表現機構の第 2 世代 (docs/stage017-gcc.md 5.7)
 *
 * `re1` を作り直したもの。作り直した理由は 3 つある。
 *
 *   1. **awk は ERE を使う** —— `|` `+` `?` `(` `)` `{n,m}` が素の字で
 *      書かれる。re1 は BRE 専用で，選択 (`|`) をそもそも受けない。
 *   2. **re1 は組の中へ後戻りできなかった。** `\(a*\)ab` は "aab" に
 *      合うべきだが，組が貪欲に "aa" を取ったあと，続きが外れても組の
 *      取り方を試し直せずに外れていた (5.7)。
 *   3. **re1 は組の番号を組み直しても戻していなかった。** 台本の中で
 *      2 つめの命令が組を使うと，`\1` が別の組を指していた (5.7)。
 *
 * 中身は節の木ではなく**命令列**にした (SPLIT / JMP / SAVE / MATCH)。
 * 後戻りは命令列を辿る再帰で行う。この形なら，選択も組の中への後戻りも
 * 同じ 1 つの仕組みで済む。
 *
 * 受ける形 (BRE):  ^ $ . *  [...] [^...] [a-z] [[:alpha:]]
 *                  \( \) \1〜\9  \+ \? \| \{n,m\}  \. \\ \n \t
 * 受ける形 (ERE):  ^ $ . * + ? | ( ) {n,m} [...]  (組の後方参照は無い)
 * 受けない形:      \< \> \b \w \W \s \S (名指しで拒む。黙って字として
 *                  扱うと「動くが違う」になる)
 *
 * 照合は最左。選択を含む形では**最長**を採る (全部辿って最長を選ぶ)。
 * 選択を含まない形では貪欲最左のまま，最初に合った形で止める ——
 * 全探索は行長の 2 乗の手数になるので，必要な形だけに限る。
 */
#ifndef RE2_H
#define RE2_H

/* 組む。成功なら先頭の命令番号 (0 以上)，誤りなら -1 を返す。
 * 誤りの理由は re_errmsg() で読む */
int re_compile(char *pat);      /* POSIX BRE (GNU の \| \+ \? \{ \} を含む) */
int re_compile_ere(char *pat);  /* POSIX ERE (awk / grep -E が使う) */

/* 行のどこかに合うか。合えば 1 を返し，*mb / *me に範囲を入れる */
int re_search(int head, char *line, char **mb, char **me);

/* 途中から探す。**行頭を別に渡す** —— ^ の判定は行の先頭を知らないと
 * できないので，探し始める位置とは分けて持つ (sed の置換が使う) */
int re_search_from(int head, char *linestart, char *from, char **mb, char **me);

/* 組 (\( \) / ( )) の n 番目が合った範囲。合っていなければ 0 */
char *re_gs(int n);
char *re_ge(int n);

/* 組んだ結果の入れ物を空にする (台本を読み直すとき) */
int re_reset(void);

/* 直前の誤りの理由 */
char *re_errmsg(void);

/* 照合の手数が上限に当たったか。**当たった照合の答は信用できない**ので，
 * 呼ぶ側は必ず見て，黙って進まずに止まること */
int re_overrun(void);

#endif
