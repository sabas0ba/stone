// libc15 の strtod の検査 (docs/stage015-tcc.md 12.25)。1 検査 1 文字。
// 期待出力: abcdefg
//
// tcc は 10 進の浮動小数点定数をこの strtod で変換する (tccpp.c の
// parse_number。多倍長の経路は 16 進の定数だけが通る)。したがって
// **ここが狂うと tcc が作る実行形式の定数が狂う**。
//
// 検査は「2 の冪」ばかりである。この strtod は 10 の冪を繰返し乗算で
// 作るので，乗算のたびに丸めが入り，一般の値では最終ビットが数 ULP
// ずれる (1e300 で 4 ULP)。2 の冪は仮数が 1 なので，18 桁の有効数字が
// 残っていれば必ず正しい値へ丸まる。tcc が使う定数 (2^64 / 2^96) は
// どちらもこの形である。
#include <stdlib.h>
#include <stdio.h>

int chk(char *s, unsigned hi, unsigned lo, int c) {
  union { double d; unsigned u[2]; } x;
  x.d = strtod(s, (char **)0);
  if (x.u[1] == hi && x.u[0] == lo) { putchar(c); return 0; }
  printf("X%s=%08x%08x ", s, x.u[1], x.u[0]);
  return 1;
}

int main(void) {
  chk("1.0", 0x3ff00000, 0x00000000, 'a');
  chk("0.5", 0x3fe00000, 0x00000000, 'b');
  chk("-2.5", 0xc0040000, 0x00000000, 'c');
  chk("4294967296.0", 0x41f00000, 0x00000000, 'd');   /* 2^32 (10 桁) */
  /* 2^64 (20 桁)。器 (18 桁) を溢れたぶんを指数へ送れないと 1/10 になる */
  chk("18446744073709551616.0", 0x43f00000, 0x00000000, 'e');
  /* 2^96 (29 桁)。溢れが 11 桁ある */
  chk("79228162514264337593543950336.0", 0x45f00000, 0x00000000, 'f');
  chk("1e19", 0x43e158e4, 0x60913d00, 'g');
  putchar('\n');
  return 0;
}
