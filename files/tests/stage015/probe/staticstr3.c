/* 入れ子の初期化子が**その対象の幅を超える**形。**拒むのが正しい。**
 *
 *     static int a[2][2] = { {1,2,3} };
 *
 * 内側の `{1,2,3}` は `int[2]` を埋めるので 3 つ目は溢れている。
 * ところが**外側にはまだ余りがある** (a[1] が空いている) ので，
 * 「出たバイト数が宣言した総量を超えたか」だけを見ていると素通りし，
 * **3 が 2 行目に入る**。溢れた側ではなく別の場所が埋まるという，
 * いちばん判りにくい壊れ方である (docs/stage017-cc.md 33.6)。
 *
 * cc15s の途中まで実際にそうなっていた。「外側で必ず捕まる」と書いて
 * レビューに返したが，**返した内容が誤っていた**。測ったら通って
 * しまった (a[1][0] が 3 になる)。
 *
 * 直しは ginit1() の配列の道で `outp - base > w` を見るだけ。
 * ここは**通ってはいけない形**なので，台帳では gap (拒む) で記録する。 */
int putc(int c);

int main() {
  static int a[2][2] = { {1,2,3} };
  putc(a[1][0] == 0 ? 'y' : 'n');
  putc('\n');
  return 0;
}
