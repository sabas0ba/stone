/* **スカラの初期化子は 1 つだけである** (C89 6.5.7)。
 *
 *     「スカラの初期化子は，単一の式でなければならない。
 *       波括弧で囲んでもよい」
 *
 * したがって
 *
 *     static int a[2][2] = { 1, {2,3}, 4 };
 *
 * の `{2,3}` は制約違反である。`1` を書いた時点で「いま埋めている
 * 対象」は a[0][1] というスカラなので，その初期化子に式が 2 つある。
 *
 * **cc15u までは黙って通し，溢れた 3 を隣へ入れていた** ——
 * 出る値は `1 2 3 4`。ホストの gcc は診断を 2 つ出したうえで
 * `1 2 4 0` にする (3 を捨て，4 を次の行の先頭へ)。
 * **制約違反に対して黙って値を作っていたのは我々だけ**だった。
 *
 * staticstr3 (`{{1,2,3}}`) と同じ壊れ方である —— 溢れた側ではなく
 * **別の場所が埋まる**。同じに 6 で拒む (cc15v)。
 *
 * **これは差分試験 (tools/diff17.sh) が見つけた。** 台帳の期待値は
 * 我々が書いているので，我々が「正しい」と思った値がそのまま期待値に
 * なっていた。staticstr2 の 12 番として **`ok` で載せてあった**
 * (docs/stage017-gcc.md 5.2)。
 *
 * 台帳では staticstr3 と同じく **ずっと gap のままでよい形**である。 */
int putc(int c);

static int a[2][2] = { 1, {2,3}, 4 };

int main() {
  putc(a[1][0] == 3 ? 'y' : 'n');
  putc('\n');
  return 0;
}
